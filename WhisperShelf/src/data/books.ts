export function getBooksPerShelf(books: Book[], shelvesCount: number): Book[][] {
  const shelves: Book[][] = Array.from({ length: shelvesCount }, () => []);
  books.forEach((book, index) => {
    shelves[index % shelvesCount].push(book);
  });
  return shelves;
}